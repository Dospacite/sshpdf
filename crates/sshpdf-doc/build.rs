//! Generates the table that maps CJK radical look-alikes to ideographs from
//! `data/UnicodeData.txt`.
//!
//! Some PDF producers (Chrome among them) map ideographs such as 文 to the
//! Kangxi radical with the same shape (⽂ U+2F42). They look the same but
//! break search and copy. UnicodeData gives each radical a compatibility
//! mapping to its ideograph.

use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let data = manifest.join("../../data/UnicodeData.txt");
    println!("cargo:rerun-if-changed={}", data.display());
    let text = std::fs::read_to_string(&data).unwrap_or_else(|e| panic!("cannot read {}: {e}", data.display()));
    let mut out = String::from("// Generated by build.rs from data/UnicodeData.txt. Do not edit.\n\n");
    out.push_str("/// (radical, ideograph), sorted.\npub(crate) const RADICALS: &[(char, char)] = &[\n");
    let mut n = 0;
    for line in text.lines() {
        let f: Vec<&str> = line.split(';').collect();
        let cp = u32::from_str_radix(f[0], 16).expect("hex");
        if !(0x2E80..=0x2FDF).contains(&cp) {
            continue;
        }
        if let Some(target) = f[5].strip_prefix("<compat> ")
            && !target.contains(' ')
        {
            let t = u32::from_str_radix(target, 16).expect("hex");
            writeln!(out, "    ('\\u{{{cp:X}}}', '\\u{{{t:X}}}'),").expect("write");
            n += 1;
        }
    }
    assert!(n > 200, "expected the Kangxi radicals, found {n}");
    out.push_str("];\n");
    let path = PathBuf::from(std::env::var("OUT_DIR").expect("out dir")).join("radicals.rs");
    std::fs::write(path, out).expect("write radicals table");
}
