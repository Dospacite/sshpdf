//! Generates the box-drawing junction table from `data/UnicodeData.txt`.
//!
//! Every "BOX DRAWINGS ..." character made of straight lines from the cell
//! centre to its edges is described by the weight of its arm in each
//! direction (up, down, left, right): none, light, heavy or double. Names
//! give the weights before ("LIGHT DOWN AND RIGHT") or after the directions
//! ("DOWN LIGHT AND RIGHT HEAVY"); HORIZONTAL and VERTICAL stand for two
//! directions. Dashed lines, arcs and diagonals are skipped.

use std::collections::HashMap;
use std::fmt::Write as _;
use std::path::PathBuf;

const NONE: u8 = 0;
const LIGHT: u8 = 1;
const HEAVY: u8 = 2;
const DOUBLE: u8 = 3;

/// Arms (up, down, left, right) from a box-drawing name, if it is a plain
/// junction.
fn parse(name: &str) -> Option<[u8; 4]> {
    let rest = name.strip_prefix("BOX DRAWINGS ")?;
    let mut arms = [NONE; 4];
    let mut pending: Vec<usize> = Vec::new();
    let mut prefix: Option<u8> = None;
    for tok in rest.split(' ') {
        let weight = match tok {
            "LIGHT" | "SINGLE" => Some(LIGHT),
            "HEAVY" => Some(HEAVY),
            "DOUBLE" => Some(DOUBLE),
            _ => None,
        };
        if let Some(w) = weight {
            if pending.is_empty() {
                prefix = Some(w);
            } else {
                for d in pending.drain(..) {
                    arms[d] = w;
                }
            }
            continue;
        }
        let dirs: &[usize] = match tok {
            "UP" => &[0],
            "DOWN" => &[1],
            "LEFT" => &[2],
            "RIGHT" => &[3],
            "VERTICAL" => &[0, 1],
            "HORIZONTAL" => &[2, 3],
            "AND" => &[],
            // DASH, ARC, DIAGONAL, ...: not a plain junction.
            _ => return None,
        };
        for &d in dirs {
            match prefix {
                Some(w) => arms[d] = w,
                None => pending.push(d),
            }
        }
    }
    if !pending.is_empty() || arms == [NONE; 4] {
        return None;
    }
    Some(arms)
}

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let data = manifest.join("../../data/UnicodeData.txt");
    println!("cargo:rerun-if-changed={}", data.display());
    let text = std::fs::read_to_string(&data).unwrap_or_else(|e| panic!("cannot read {}: {e}", data.display()));

    let mut table: HashMap<[u8; 4], u32> = HashMap::new();
    for line in text.lines() {
        let mut f = line.split(';');
        let cp = u32::from_str_radix(f.next().expect("code point"), 16).expect("hex");
        let name = f.next().expect("name");
        if !(0x2500..=0x257F).contains(&cp) {
            continue;
        }
        if let Some(arms) = parse(name) {
            let prev = table.insert(arms, cp);
            assert!(prev.is_none(), "two characters for {arms:?}: U+{cp:04X}");
        }
    }
    // Sanity checks of the parser against well-known characters.
    let expect = [
        ([NONE, NONE, LIGHT, LIGHT], 0x2500u32),    // ─
        ([LIGHT, LIGHT, NONE, NONE], 0x2502),       // │
        ([NONE, LIGHT, NONE, LIGHT], 0x250C),       // ┌
        ([LIGHT, LIGHT, LIGHT, LIGHT], 0x253C),     // ┼
        ([NONE, LIGHT, NONE, HEAVY], 0x250D),       // ┍ down light and right heavy
        ([NONE, NONE, HEAVY, HEAVY], 0x2501),       // ━
        ([DOUBLE, DOUBLE, DOUBLE, DOUBLE], 0x256C), // ╬
        ([LIGHT, LIGHT, DOUBLE, DOUBLE], 0x256A),   // ╪ vertical single and horizontal double
        ([NONE, NONE, LIGHT, HEAVY], 0x257C),       // ╼ light left and heavy right
        ([NONE, NONE, LIGHT, NONE], 0x2574),        // ╴ light left
    ];
    for (arms, cp) in expect {
        assert_eq!(table.get(&arms), Some(&cp), "parser: {arms:?} should be U+{cp:04X}");
    }
    // All light/heavy combinations of four arms exist (3^4 - 1 = 80).
    let light_heavy = table.keys().filter(|a| a.iter().all(|&w| w != DOUBLE)).count();
    assert_eq!(light_heavy, 80, "light/heavy junctions");

    let mut entries: Vec<([u8; 4], u32)> = table.into_iter().collect();
    entries.sort();
    let mut out = String::new();
    out.push_str("// Generated by build.rs from data/UnicodeData.txt. Do not edit.\n\n");
    out.push_str("/// (arms [up, down, left, right] with 0 none, 1 light, 2 heavy, 3 double; char)\n");
    out.push_str("pub(crate) const BOX_CHARS: &[([u8; 4], char)] = &[\n");
    for (arms, cp) in entries {
        writeln!(out, "    ({arms:?}, '\\u{{{cp:X}}}'),").expect("write");
    }
    out.push_str("];\n");
    let out_path = PathBuf::from(std::env::var("OUT_DIR").expect("out dir")).join("box_chars.rs");
    std::fs::write(out_path, out).expect("write box table");
}
